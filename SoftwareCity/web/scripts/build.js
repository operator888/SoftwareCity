// Build script: bundles src/ into dist/ with esbuild.
// Two modes:
//   production  - minified, content-hashed bundle name, full library bundled inline
//   development - unminified, inline sourcemap; with --watch, rebuilds on save
//
// Everything the page needs ends up inside dist/: one JS bundle (app code +
// three.js + OrbitControls + dagre, see src/js/vendor.js), the CSS, the
// self-hosted fonts, the parser fixtures, and a copy of the app's own source
// under dist/src/ so the "Software City itself" action can survey it offline.
//
// The pattern library and the starport sample are read from the monorepo's
// shared/ folder and written to src/data/_generated/ before bundling.

import * as esbuild from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, statSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const src = resolve(root, 'src');
const dist = resolve(root, 'dist');
const monorepoRoot = resolve(root, '..', '..');
const shared = resolve(monorepoRoot, 'shared');
const mode = (process.argv.find(a => a.startsWith('--mode=')) || '--mode=production').slice(7);
const watch = process.argv.includes('--watch');
const minify = mode === 'production';
const define = { 'process.env.NODE_ENV': JSON.stringify(mode) };

function copyDir(from, to, filter) {
  if (!existsSync(from)) return;
  mkdirSync(to, { recursive: true });
  for (const entry of readdirSync(from)) {
    const s = join(from, entry);
    const t = join(to, entry);
    if (statSync(s).isDirectory()) copyDir(s, t, filter);
    else if (!filter || filter(s)) copyFileSync(s, t);
  }
}

async function buildLibrary() {
  const libraryDir = resolve(shared, 'library');
  const familyFiles = readdirSync(libraryDir).filter(f => f.endsWith('.js')).sort();
  const families = [];
  const patterns = [];
  for (const file of familyFiles) {
    const mod = await import(resolve(libraryDir, file).replace(/\\/g, '/'));
    const data = mod.default;
    families.push(...data.families);
    for (const p of data.patterns) patterns.push(p);
  }
  const seenF = new Set();
  const familiesUnique = families.filter(f => seenF.has(f) ? false : (seenF.add(f), true));
  const seenP = new Set();
  const patternsUnique = patterns.filter(p => seenP.has(p.id) ? false : (seenP.add(p.id), true));
  return { families: familiesUnique, patterns: patternsUnique };
}

async function buildStarport() {
  /* shared/starport/index.js is an ES module exporting the manifest
     { "<user-facing path>": { file: "<path under files/>" } }. Import it
     instead of regex-parsing it, so a reformat can never break the build. */
  const starportDir = resolve(shared, 'starport');
  const filesDir = resolve(starportDir, 'files');
  const manifest = (await import(resolve(starportDir, 'index.js').replace(/\\/g, '/'))).default;
  const out = { _manifest: { name: 'starport', description: 'Starport sample' } };
  for (const [path, meta] of Object.entries(manifest)) {
    if (path === '_manifest') continue;
    const onDisk = resolve(filesDir, meta.file);
    if (!existsSync(onDisk)) { console.warn('starport: missing', onDisk); continue; }
    out[path] = readFileSync(onDisk, 'utf8');
  }
  return out;
}

const library = await buildLibrary();
const starport = await buildStarport();

// Write generated library/starport modules that the bundle imports.
mkdirSync(resolve(src, 'data', '_generated'), { recursive: true });
writeFileSync(resolve(src, 'data', '_generated', 'library.js'),
  `// Auto-generated by scripts/build.js. Do not edit.\nexport default ${JSON.stringify(library)};\n`);
writeFileSync(resolve(src, 'data', '_generated', 'starport.js'),
  `// Auto-generated by scripts/build.js. Do not edit.\nexport default ${JSON.stringify(starport)};\n`);

// Clean previous output.
if (existsSync(dist)) rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// Static assets.
copyDir(resolve(src, 'css'), resolve(dist, 'css'));
copyDir(resolve(root, 'assets', 'fonts'), resolve(dist, 'fonts'));
copyDir(resolve(root, 'tests', 'fixtures'), resolve(dist, 'fixtures'));

// The app's own source, for the "Software City itself" action (fetched at runtime
// relative to index.html). Generated data files are skipped: they are large
// and not interesting to survey.
copyDir(resolve(src, 'js'), resolve(dist, 'src', 'js'));
copyDir(resolve(src, 'css'), resolve(dist, 'src', 'css'));
copyFileSync(resolve(src, 'index.js'), resolve(dist, 'src', 'index.js'));
copyFileSync(resolve(src, 'index.html'), resolve(dist, 'src', 'index.html'));
copyDir(resolve(shared, 'parser'), resolve(dist, 'src', 'parser'));
writeFileSync(resolve(dist, 'src', 'manifest.json'), JSON.stringify({
  files: [
    'src/index.html', 'src/index.js',
    ...readdirSync(resolve(src, 'js')).filter(f => f.endsWith('.js')).map(f => 'src/js/' + f),
    ...readdirSync(resolve(shared, 'parser')).filter(f => f.endsWith('.js')).map(f => 'src/parser/' + f),
    ...readdirSync(resolve(src, 'css')).filter(f => f.endsWith('.css')).map(f => 'src/css/' + f)
  ]
}));

function writeIndex(bundleName) {
  let html = readFileSync(resolve(src, 'index.html'), 'utf8');
  if (bundleName !== 'app.js') html = html.replace('src="app.js"', 'src="' + bundleName + '"');
  writeFileSync(resolve(dist, 'index.html'), html);
}

const buildOptions = {
  entryPoints: [resolve(src, 'index.js')],
  bundle: true,
  outfile: resolve(dist, 'app.js'),
  format: 'iife',
  platform: 'browser',
  target: ['chrome120', 'firefox120', 'safari17', 'edge120'],
  minify,
  sourcemap: mode === 'development' ? 'inline' : true,
  define,
  legalComments: 'inline',
  logLevel: 'info',
  loader: { '.js': 'js', '.json': 'json' },
  treeShaking: true
};

if (watch) {
  /* Watch mode writes straight to dist/app.js on every change; index.html
     references the unhashed name, so the dev server picks up each rebuild. */
  writeIndex('app.js');
  const ctx = await esbuild.context(buildOptions);
  await ctx.watch();
  console.log('Watching for changes… (dist/app.js)');
} else {
  const result = await esbuild.build(buildOptions);
  if (result.errors?.length) process.exit(1);
  let bundleName = 'app.js';
  if (mode === 'production') {
    const appPath = resolve(dist, 'app.js');
    const hash = createHash('sha256').update(readFileSync(appPath)).digest('hex').slice(0, 10);
    bundleName = `app.${hash}.js`;
    copyFileSync(appPath, resolve(dist, bundleName));
    rmSync(appPath);
    if (existsSync(appPath + '.map')) { copyFileSync(appPath + '.map', resolve(dist, bundleName + '.map')); rmSync(appPath + '.map'); }
  }
  writeIndex(bundleName);
  console.log(`Built → ${dist}  (${bundleName})`);
}
