// Reads shared/starport/index.js + shared/starport/files/* and writes
// SoftwareCity/web/src/data/_generated/starport.js as a single ESM module
// that exports the inlined { path: text } object. Run before tests
// and before build.
//
// The manifest in shared/starport/index.js is a JSON-like object
// whose keys are the user-facing paths (e.g. "starport/game/ship.gd")
// and whose values are { file: "starport/game/ship.gd" } — the path
// of the actual file on disk under shared/starport/files/. The
// "file" key may point at a nested file or a flat one; we resolve
// it relative to the manifest's `files/` directory.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const __dirname = dirname(fileURLToPath(import.meta.url));
const monorepoRoot = resolve(__dirname, '..', '..', '..');
const starportDir = resolve(monorepoRoot, 'shared', 'starport');
const filesDir = resolve(starportDir, 'files');
const outDir = resolve(monorepoRoot, 'SoftwareCity', 'web', 'src', 'data', '_generated');
mkdirSync(outDir, { recursive: true });
const out = { _manifest: { name: 'starport', description: 'Starport sample' } };
if (!existsSync(filesDir)) { console.error('no starport files dir at', filesDir); process.exit(1); }
/* The manifest is an ES module; import it rather than eval-ing its text. */
const manifest = (await import(resolve(starportDir, 'index.js').replace(/\\/g, '/'))).default;
if (!manifest) { console.error('manifest has no default export'); process.exit(1); }
for (const [path, meta] of Object.entries(manifest)) {
  if (path === '_manifest') continue;
  const onDisk = resolve(filesDir, meta.file);
  if (!existsSync(onDisk)) { console.warn('missing:', onDisk); continue; }
  out[path] = readFileSync(onDisk, 'utf8');
}
writeFileSync(resolve(outDir, 'starport.js'),
  `// Auto-generated by scripts/inline-starport.js. Do not edit.\nexport default ${JSON.stringify(out)};\n`);
console.log('inlined', Object.keys(out).length - 1, 'starport files');
