// Writes the pattern library and the starport sample as standalone data
// files, for consumers that want the data without the app (a docs site, a
// CLI, the Edu product's content service). Reads from the monorepo's
// shared/ folder — the single source of truth — never from src/.
//
// Output:
//   src/data/_generated/library.js   ESM, imported by the web bundle
//   src/data/_generated/starport.js  ESM, imported by the web bundle
//   dist/data/library.js             classic script, sets window.CP_LIBRARY
//   dist/data/library.json           plain JSON
//
// Usage: node scripts/build-library.js

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const shared = resolve(root, '..', '..', 'shared');
const gen = resolve(root, 'src', 'data', '_generated');
const dist = resolve(root, 'dist', 'data');

mkdirSync(gen, { recursive: true });
mkdirSync(dist, { recursive: true });

const families = [];
const patterns = [];
const libraryDir = resolve(shared, 'library');
for (const file of readdirSync(libraryDir).filter(f => f.endsWith('.js')).sort()) {
  const mod = await import(resolve(libraryDir, file).replace(/\\/g, '/'));
  families.push(...mod.default.families);
  patterns.push(...mod.default.patterns);
}
const seenF = new Set();
const familiesUnique = families.filter(f => seenF.has(f) ? false : (seenF.add(f), true));
const seenP = new Set();
const patternsUnique = patterns.filter(p => seenP.has(p.id) ? false : (seenP.add(p.id), true));
const lib = { families: familiesUnique, patterns: patternsUnique };

const starportDir = resolve(shared, 'starport');
const manifest = (await import(resolve(starportDir, 'index.js').replace(/\\/g, '/'))).default;
const starport = { _manifest: { name: 'starport', description: 'Starport sample' } };
for (const [path, meta] of Object.entries(manifest)) {
  if (path === '_manifest') continue;
  const onDisk = resolve(starportDir, 'files', meta.file);
  if (existsSync(onDisk)) starport[path] = readFileSync(onDisk, 'utf8');
}

writeFileSync(resolve(gen, 'library.js'), `// Auto-generated by scripts/build-library.js. Do not edit.\nexport default ${JSON.stringify(lib)};\n`);
writeFileSync(resolve(gen, 'starport.js'), `// Auto-generated by scripts/build-library.js. Do not edit.\nexport default ${JSON.stringify(starport)};\n`);
writeFileSync(resolve(dist, 'library.js'), `// Auto-generated. Dual-licensed under PolyForm Noncommercial 1.0.0 + commercial licence.\nwindow.CP_LIBRARY = ${JSON.stringify(lib)};\n`);
writeFileSync(resolve(dist, 'library.json'), JSON.stringify(lib));
writeFileSync(resolve(dist, 'starport.js'), `// Auto-generated.\nwindow.CP_STARPORT = ${JSON.stringify(starport)};\n`);

console.log(`Wrote ${patternsUnique.length} pattern(s), ${familiesUnique.length} famil${familiesUnique.length === 1 ? 'y' : 'ies'}, ${Object.keys(starport).length - 1} starport file(s).`);
